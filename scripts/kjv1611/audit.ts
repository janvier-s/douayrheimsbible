// Writes docs/audits/kjv-1611-long-s.md from the evidence, calibration and conflicts files.
// Usage: npx tsx scripts/kjv1611/audit.ts <rule-only dir> <final dir>
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { homedir } from 'os';
import { join, dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const HOME = join(homedir(), 'facsimiles/kjv-1611');
const [ruleDir, finalDir] = process.argv.slice(2).map((d) => resolve(d));
const cal = JSON.parse(readFileSync(join(HOME, 'calibration.json'), 'utf8'));
const pol = JSON.parse(readFileSync(join(HOME, 'cluster-policy.json'), 'utf8'));
const conflictsPath = join(HOME, 'conflicts.tsv');
const conflicts = existsSync(conflictsPath)
	? readFileSync(conflictsPath, 'utf8').trim().split('\n').slice(1).filter(Boolean)
	: [];
const pct = (r: { agree: number; sPositions: number }) =>
	((100 * r.agree) / r.sPositions).toFixed(2);
const before = cal.results[ruleDir];
const after = cal.results[finalDir];

const sections = ['OT', 'APOC', 'NT'];
const clusterRows = ['f', 'h', 'k', 'b']
	.map((k) => {
		const cells = sections.map((s) => {
			const c = pol.clusters?.[s]?.[k] ?? { long: 0, round: 0 };
			const d = pol.policy?.[s]?.[k] ?? 'undecided (round)';
			return `${d} (${c.long} long / ${c.round} round)`;
		});
		return `| s+${k} | ${cells.join(' | ')} |`;
	})
	.join('\n');

const md = `# KJV 1611: long s (ſ) audit

Generated by \`scripts/kjv1611/audit.ts\`. Data: \`static/data/kjv-1611/\`.

## Method

1. **Rule.** A lowercase s that is not word-final becomes ſ; a word-final s stays round; capitals are unchanged.
   Final means the next visible character (tags skipped) is not a letter.
2. **Clusters.** s before f, h, k and b is not settled by the rule. It is decided per book section
   (OT / Apocrypha / NT) by majority of the OCR readings, with at least 20 readings, or at least 5 readings that are unanimous; otherwise it stays round.
3. **Evidence.** Every 1611 page image (kingjamesbibleonline.org) is read with local Tesseract (\`eng\`, 3× upscale,
   \`--psm 1\`). OCR words are aligned to the verse words (banded longest common subsequence on OCR-folded
   keys). At each s, an OCR l/f/ſ means long and an OCR s means round.
4. **Per-word overrides.** Where a reading has Tesseract confidence ≥ 80 and disagrees with the rule or the
   cluster policy, the reading wins. Readings below 80 that disagree are listed under *Conflicts*.
5. **Calibration.** The result is compared letter for letter with the proofread Wikisource pages of the 1611
   Bible (quality ≥ 3): ${cal.pages} pages, ${cal.verses} verses, matched to our verses by chapter, verse and text.

## OCR evidence

Readings: ${pol.counts?.long ?? '?'} long, ${pol.counts?.round ?? '?'} round, ${pol.counts?.none ?? '?'} no reading (word not aligned or not legible).

## Cluster policy

| cluster | OT | Apocrypha | NT |
|---|---|---|---|
${clusterRows}

## Calibration against Wikisource

| text | s positions compared | agree | agreement |
|---|---|---|---|
| rule only (clusters round) | ${before?.sPositions} | ${before?.agree} | ${before ? pct(before) : '?'}% |
| final (policy + overrides) | ${after?.sPositions} | ${after?.agree} | ${after ? pct(after) : '?'}% |

Target ≥ 99.5%. Remaining disagreements are in \`~/facsimiles/kjv-1611/wikisource-disagreements.1.tsv\`;
the ones inspected are Wikisource's own transcription choices (for example Christ for Chriſt).

## Verses without 1611 text

Neither source has the 1611 text of these verses, so they keep the modern KJV wording and are flagged
\`"modern": true\` in the data: the Additions to Esther (Esther 10:4 to 16:24, 105 verses), Daniel 3:24, and the
verses the 1611 source leaves blank in Ecclesiasticus. The 1611 has no Psalm titles, so none appear in this text.

## Conflicts

${conflicts.length} words where the rule and the OCR disagree but the reading is below confidence 80.
Format: book, chapter:verse, character offset, word, rule, OCR, confidence. Check by eye if wanted.

\`\`\`
${conflicts
	.slice(0, 400)
	.map((l) => {
		const c = l.split('\t');
		return `${c[0]} ${c[1]}:${c[2]} @${c[3]} ${c[4]} rule=${c[5]} ocr=${c[6]} conf=${Math.round(+c[7])}`;
	})
	.join('\n')}
\`\`\`
${conflicts.length > 400 ? `\n…and ${conflicts.length - 400} more in \`~/facsimiles/kjv-1611/conflicts.tsv\`.\n` : ''}`;

mkdirSync(join(ROOT, 'docs/audits'), { recursive: true });
writeFileSync(join(ROOT, 'docs/audits/kjv-1611-long-s.md'), md);
console.log('wrote docs/audits/kjv-1611-long-s.md');
